'use client';

import { useMutation } from '@tanstack/react-query';
import { toast } from 'sonner';
import { ExportButton } from '@/components/buttons/export-button';
import { exportCustomersPdf, exportCustomersExcel } from '../api/service';
import { useCustomerFilters } from '../hooks/use-customer-filters';

function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  link.click();
  URL.revokeObjectURL(url);
}

export function CustomerExportButtons() {
  const filters = useCustomerFilters();

  const pdfMutation = useMutation({
    mutationFn: () => exportCustomersPdf(filters),
    onSuccess: (blob) => downloadBlob(blob, `customers-${Date.now()}.pdf`),
    onError: () => toast.error('Failed to export PDF')
  });

  const excelMutation = useMutation({
    mutationFn: () => exportCustomersExcel(filters),
    onSuccess: (blob) => downloadBlob(blob, `customers-${Date.now()}.xlsx`),
    onError: () => toast.error('Failed to export Excel')
  });

  const isPending = pdfMutation.isPending || excelMutation.isPending;

  return (
    <ExportButton
      onExportPdf={() => pdfMutation.mutate()}
      onExportExcel={() => excelMutation.mutate()}
      isPending={isPending}
    />
  );
}
