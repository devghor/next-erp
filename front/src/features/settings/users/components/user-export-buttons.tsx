'use client';

import { useMutation } from '@tanstack/react-query';
import { toast } from 'sonner';
import { ExportButton } from '@/components/buttons/export-button';
import { exportUsersPdf, exportUsersExcel } from '../api/service';
import { useUserFilters } from '../hooks/use-user-filters';

function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  link.click();
  URL.revokeObjectURL(url);
}

export function UserExportButtons() {
  const filters = useUserFilters();

  const pdfMutation = useMutation({
    mutationFn: () => exportUsersPdf(filters),
    onSuccess: (blob) => downloadBlob(blob, `users-${Date.now()}.pdf`),
    onError: () => toast.error('Failed to export PDF')
  });

  const excelMutation = useMutation({
    mutationFn: () => exportUsersExcel(filters),
    onSuccess: (blob) => downloadBlob(blob, `users-${Date.now()}.xlsx`),
    onError: () => toast.error('Failed to export Excel')
  });

  const isPending = pdfMutation.isPending || excelMutation.isPending;

  return (
    <ExportButton
      onExportPdf={() => pdfMutation.mutate()}
      onExportExcel={() => excelMutation.mutate()}
      isPending={isPending}
    />
  );
}
